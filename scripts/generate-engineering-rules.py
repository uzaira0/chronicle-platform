#!/usr/bin/env python3
"""Derive the engineering-rule inventory and require positive and negative fixtures."""

import argparse
import re
import sys
from pathlib import Path

import yaml


def documents(path):
    return list(yaml.safe_load_all(path.read_text(encoding="utf-8")))


def yaml_files(directory):
    return sorted(path for path in directory.rglob("*") if path.suffix in (".yml", ".yaml"))


def inventory(root):
    rows = []
    for config_path in [root / "sgconfig.yml", *sorted(root.glob("*/sgconfig.yml"))]:
        config = documents(config_path)[0]
        fixtures = {}
        for test in config.get("testConfigs", []):
            for path in yaml_files(config_path.parent / test["testDir"]):
                for fixture in documents(path):
                    fixtures.setdefault(fixture["id"], []).append(fixture)
        for directory in config["ruleDirs"]:
            for path in yaml_files(config_path.parent / directory):
                for rule in documents(path):
                    note = rule.get("note")
                    if not isinstance(note, str) or "Blind spots" not in note:
                        raise ValueError(f'{path.relative_to(root)}: {rule["id"]}: missing Blind spots note')
                    for kind in ("valid", "invalid"):
                        if not any(fixture.get(kind) for fixture in fixtures.get(rule["id"], [])):
                            raise ValueError(f'{path.relative_to(root)}: {rule["id"]}: missing {kind} fixtures')
                    rows.append((rule["id"], rule["message"], "ast-grep", path.relative_to(root).as_posix()))
    annotations = {kind: set() for kind in ("ruleid", "ok")}
    for path in (root / "tests/security/semgrep-tests").rglob("*"):
        if path.is_file():
            for kind, names in re.findall(r"(?:#|//)\s*(ruleid|ok):\s*([^\n]+)", path.read_text(encoding="utf-8")):
                annotations[kind].update(name.strip() for name in names.split(","))
    for path in yaml_files(root / "tests/security/semgrep"):
        for document in documents(path):
            for rule in document["rules"]:
                for kind, ids in annotations.items():
                    if rule["id"] not in ids:
                        raise ValueError(f'{path.relative_to(root)}: {rule["id"]}: missing {kind} fixtures')
                rows.append((rule["id"], rule["message"], "semgrep", path.relative_to(root).as_posix()))
    return rows


def render(rows):
    lines = ["<!-- Generated by scripts/generate-engineering-rules.py; edit rule YAML and regenerate. -->", ""]
    for row in sorted(rows, key=lambda row: (row[2], row[3], row[0])):
        lines.append(" | ".join(" ".join(str(value).split()).replace("|", "\\|") for value in row))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = args.root / "docs/engineering-rules.md"
    try:
        generated = render(inventory(args.root))
        if args.check:
            if not output.exists() or output.read_text(encoding="utf-8") != generated:
                raise ValueError("docs/engineering-rules.md is stale; run python3 scripts/generate-engineering-rules.py")
        else:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(generated, encoding="utf-8")
    except (KeyError, ValueError, OSError, yaml.YAMLError) as error:
        print(error, file=sys.stderr)
        return 1
    print(f"Engineering rule inventory: {len(generated.splitlines()) - 2} rules; fixtures complete")
    return 0


if __name__ == "__main__":
    sys.exit(main())
