#!/usr/bin/env bash
# Self-hosted Renovate for the Chronicle repositories (docs/SUPPLY-CHAIN.md).
#
#   scripts/renovate-run.sh [--dry-run=full|lookup|extract [--base-branch NAME]] [--log FILE]
#
# --base-branch replaces renovate.json's deps/auto for a dry run only, to preview a branch that is not
# deps/auto yet (a dry run creates nothing, so it never needs deps/auto to exist).
#
# Runs the digest-pinned Renovate image below against CHRONICLE_RENOVATE_REPOSITORIES (default: the
# root repository and chronicle-web-dev). This checkout's renovate.json is the whole repository
# config, passed as Renovate's global config with requireConfig=ignored, so a renovate.json on any
# branch of the target repositories (main still carries the pre-policy one) never applies.
#
# Why one run per repository rather than cloneSubmodules: Renovate commits only to the repository it
# runs on, and cloneSubmodules only clones (docs: "cloneSubmodules"), so it cannot update a lockfile
# that lives in a submodule. chronicle-web's package.json and bun.lock live in chronicle-web-dev, so
# that repository gets its own run; the root run does not clone submodules. Gradle lockfiles in the
# JVM submodules are regenerated by scripts/dependency-gate-runner.py in the dependency sandbox.
#
# Renovate holds the GitHub token, so it executes no repository or dependency code: it only edits pins
# and pushes renovate/* branches. renovate.json sets skipArtifactsUpdate (no lockfile, go.sum or
# Gradle lock update, so no package manager, no `go` and no toolchain download runs in this
# container) and has no postUpdateOptions; allowedCommands and allowedUnsafeExecutions are empty (no
# postUpgradeTasks, no Gradle wrapper) and package-manager scripts stay off. automerge is false:
# deps/auto moves only when scripts/dependency-gate-runner.py has gated a branch. Lockfiles, go.sum,
# verification metadata and derived pins are regenerated by the gate runner in the dependency
# sandbox, which holds no credential.
#
# The token comes from `gh auth token` (CHRONICLE_RENOVATE_GH_USER picks another gh account, e.g. one
# whose token is a fine-grained token limited to the two -dev repositories: Contents, Pull requests
# and Issues read/write, nothing else) and reaches the container only as an environment variable
# copied by name (`docker run -e RENOVATE_TOKEN`), never on a command line or in a file, and is not
# printed. The log is passed through a redaction filter.
set -euo pipefail

RENOVATE_IMAGE='renovate/renovate:44.178.3@sha256:3d11682cbd374f66d770dbe5f55559053eb67267a2b5d64e7903d5ebdbd13f43'
root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)
dry_run=''
log_file=''
base_branch=''
while [[ $# -gt 0 ]]; do
  case "$1" in
    --dry-run=full|--dry-run=lookup|--dry-run=extract) dry_run=${1#--dry-run=}; shift ;;
    --log) log_file=$2; shift 2 ;;
    --base-branch) base_branch=$2; shift 2 ;;
    *) echo 'usage: scripts/renovate-run.sh [--dry-run=full|lookup|extract [--base-branch NAME]] [--log FILE]' >&2; exit 2 ;;
  esac
done
[[ -z "$base_branch" || -n "$dry_run" ]] || { echo 'renovate-run: --base-branch is for dry runs only' >&2; exit 2; }
state="${CHRONICLE_RENOVATE_HOME:-$HOME/Library/Application Support/chronicle-renovate}"
log_dir="${CHRONICLE_RENOVATE_LOG_DIR:-$HOME/Library/Logs/chronicle-dependency-intake}"
repositories="${CHRONICLE_RENOVATE_REPOSITORIES:-uzaira0/methodic-dev uzaira0/chronicle-web-dev}"
# Renovate's package and repository caches persist in this Docker volume between runs.
umask 077
mkdir -p "$state" "$log_dir"
log_file=${log_file:-$log_dir/renovate-$(date -u +%Y%m%dT%H%M%SZ)${dry_run:+-dry-run-$dry_run}.log}

for tool in docker gh python3; do
  command -v "$tool" >/dev/null || { echo "renovate-run: missing tool: $tool" >&2; exit 1; }
done

# Global config = this checkout's renovate.json + the self-hosted settings that only an admin may set.
config="$state/config.json"
python3 - "$root/renovate.json" "$config" "$dry_run" "$repositories" "$base_branch" <<'PY'
import json
import os
import sys

source, target, dry_run, repositories, base_branch = sys.argv[1:]
with open(source, encoding='utf-8') as handle:
    config = json.load(handle)
config.pop('$schema', None)
config.update({
    'platform': 'github',
    'repositories': repositories.split(),
    'requireConfig': 'ignored',
    'onboarding': False,
    'cloneSubmodules': False,
    'allowedCommands': [],
    'allowedUnsafeExecutions': [],
    # Repeated from renovate.json so no repository config can turn them back on: Renovate runs no
    # package manager and merges nothing.
    'skipArtifactsUpdate': True,
    'automerge': False,
    'allowScripts': False,
    'binarySource': 'install',
    'persistRepoData': False,
    'gitAuthor': 'Chronicle Renovate <renovate@users.noreply.github.com>',
    # Docker Hub answers 403 to anonymous tag page 11 (100 per page), and Renovate then drops every
    # tag and its timestamp, so timestamp-required holds the image forever. Ten pages are the
    # 1000 most recently pushed tags, which hold every release Renovate would propose. Renovate's
    # package cache keeps such a failed lookup: after a 403 run, start from a new cache volume.
    'dockerMaxPages': 10,
})
if dry_run:
    config['dryRun'] = dry_run
if base_branch:
    config['baseBranchPatterns'] = [base_branch]
part = target + '.part'
with open(part, 'w', encoding='utf-8') as handle:
    json.dump(config, handle, indent=2)
os.replace(part, target)
PY

RENOVATE_TOKEN=$(gh auth token ${CHRONICLE_RENOVATE_GH_USER:+--user "$CHRONICLE_RENOVATE_GH_USER"})
[[ -n "$RENOVATE_TOKEN" ]] || { echo 'renovate-run: gh auth token returned nothing; run gh auth login' >&2; exit 1; }
export RENOVATE_TOKEN
export GITHUB_COM_TOKEN=$RENOVATE_TOKEN

# Redact anything shaped like a GitHub token, in case a tool prints one Renovate did not mask.
redact() { sed -E 's/(gh[pousr]_|github_pat_)[A-Za-z0-9_]{20,}/\1***redacted***/g'; }

status=0
docker run --rm --init \
  --cap-drop ALL --security-opt no-new-privileges \
  -e RENOVATE_TOKEN -e GITHUB_COM_TOKEN \
  -e RENOVATE_CONFIG_FILE=/config/config.json \
  -e LOG_LEVEL="${CHRONICLE_RENOVATE_LOG_LEVEL:-${dry_run:+debug}}" \
  -e LOG_FORMAT=json \
  -v "$config:/config/config.json:ro" \
  -v "${CHRONICLE_RENOVATE_CACHE_VOLUME:-chronicle-renovate-cache}:/tmp/renovate" \
  "$RENOVATE_IMAGE" 2>&1 | redact >"$log_file" || status=$?
unset RENOVATE_TOKEN GITHUB_COM_TOKEN
printf 'renovate-run: exit %s, log %s\n' "$status" "$log_file"
exit "$status"
