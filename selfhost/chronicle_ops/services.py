"""Which configured services are optional monitoring, and starting them without gating Chronicle;
which networks have no way off the host, and which services may stand at the edge.

A service is monitoring when the selected configuration has it only because overlays/monitoring.yml
is selected: Compose itself answers by listing the services with and without that overlay. This
works for any release's files, including an older release that a rollback restarts, and a service
added to the overlay is classified without being registered anywhere else.

INTERNAL_NETWORKS and EDGE_SERVICES are the one list of the network design (docs/NETWORK-EGRESS.md).
verify.py's service contract, the conftest policy (tests/security/policies/egress_services.rego,
generated by scripts/generate-egress-rego.py), the Compose tests and tests/security/selfhost-egress.sh
all read them from here.
"""
import os
import subprocess
from pathlib import Path

from .common import PREPARATION_TIMEOUT_SECONDS, compose, warn
from .egress import BLACKHOLE_RESOLVER

# Networks Compose creates with `internal: true`: Docker gives them no gateway route, so nothing
# that joins only these can open a connection off the host, whoever routes its subnet upstream.
INTERNAL_NETWORKS = ("core", "ingress", "database", "database-probe", "monitoring", "monitoring-ingress",
                     "docker-api", "egress-clients")

# The services that may join a network with a way off the host, and why. Every other service
# joins internal networks only or has network_mode: none.
FORWARDER = ("Holds published ports, which Docker opens only on a network it connects to the host, and "
             "copies TCP to {target} over an internal network; no data, credentials or volumes, "
             "standard-library Go only (selfhost/caddy/forward); its bridge does not masquerade and "
             "it resolves no external name")
EDGE_SERVICES = {
    "web-forward": FORWARDER.format(target="web"),
    "monitoring-forward": FORWARDER.format(target="Grafana and Fluent Bit"),
    "egress-proxy": "The one container with a route out: an HTTP CONNECT proxy (chronicle-forward -connect) that "
                    "tunnels only to the host:port pairs monitoring-config derives from .env (the public URL "
                    "public-probe checks, and an off-host alert webhook) and refuses every other target before "
                    "resolving it; no credentials, data or volume but its allowlist",
}

# One-shot jobs that copy credentials from .env into per-consumer files. Only they carry a
# credential in their Compose environment; neither has a network.
SECRET_WRITERS = ("secrets-init", "monitoring-config")


def service_networks(service):
    """Network names a Compose service definition joins; a complete definition with neither
    networks nor network_mode is on "default"."""
    networks = service.get("networks")
    if isinstance(networks, dict):
        return set(networks)
    if isinstance(networks, list):
        return set(networks)
    if service.get("network_mode") or "extends" in service or "image" not in service:
        return set()
    return {"default"}


def egress_violations(documents):
    """Problems with the network design in Compose files, each a parsed YAML mapping keyed by its
    path. Static: no Docker, no merge. Rendered configurations are checked by the tests."""
    problems = []
    networks: dict = {}
    for document in documents.values():
        networks.update((document or {}).get("networks") or {})
    for name in INTERNAL_NETWORKS:
        if name in networks and (networks[name] or {}).get("internal") is not True:
            problems.append(f"the {name} network is not internal, so its containers can reach the internet")
    for path, document in documents.items():
        for name, service in ((document or {}).get("services") or {}).items():
            outside = sorted(network for network in service_networks(service) if network not in INTERNAL_NETWORKS)
            if outside and name not in EDGE_SERVICES:
                problems.append(f"{path}:{name} joins {', '.join(outside)}, which can reach beyond the host; "
                                "only the edge services in chronicle_ops/services.py may")
            # Before Docker Engine 25.0.5 the embedded resolver of an internal network forwarded
            # external names through the host (CVE-2024-29018); the blackhole resolver closes that
            # channel on every engine.
            if "image" in service and name not in EDGE_SERVICES and service.get("network_mode") != "none" \
                    and service.get("dns") != [BLACKHOLE_RESOLVER]:
                problems.append(f"{path}:{name} has a network but not dns: [\"{BLACKHOLE_RESOLVER}\"]")
    return problems


def rego_module():
    """The conftest data module generated from the lists above (scripts/generate-egress-rego.py)."""
    import json
    lines = ["# GENERATED by scripts/generate-egress-rego.py from selfhost/chronicle_ops/services.py. Do not edit.",
             "package main", "", "import rego.v1", "",
             "internal_network_names := {" + ", ".join(json.dumps(name) for name in INTERNAL_NETWORKS) + "}", "",
             "edge_service_reasons := {"]
    lines += [f"\t{json.dumps(name)}: {json.dumps(reason)}," for name, reason in sorted(EDGE_SERVICES.items())]
    lines += ["}", "", "blackhole_resolver := " + json.dumps(BLACKHOLE_RESOLVER), "",
              "secret_writer_names := {" + ", ".join(json.dumps(name) for name in SECRET_WRITERS) + "}", ""]
    return "\n".join(lines)

# Core services an update or rollback starts but does not wait for, and why. Each is started with
# `up -d` once the waited services are healthy, its state is reported after the commit, and a
# failure only warns; `./chronicle doctor` and `./chronicle verify` report it (O10d).
UNAWAITED_BY_UPDATE = {
    "db-backup": "Healthy only after a fresh full dump passes a restore check, which can take up to "
                 "BACKUP_VERIFY_TIMEOUT_SECONDS. The update has already taken its own quiesced dump, so "
                 "waiting held participant ingress closed and rolled a good update back on a slow dump",
}

MONITORING_OVERLAY = "overlays/monitoring.yml"
# Grafana's healthcheck has a 120 s start period; a monitoring container still starting or
# unhealthy after this is reported and left to its restart policy.
MONITORING_WAIT_TIMEOUT_SECONDS = "300"
PS_FORMAT = "{{.Service}}\t{{.State}}\t{{.Health}}\t{{.ExitCode}}"


def is_monitoring_overlay(name):
    name = name.strip()
    return name == MONITORING_OVERLAY or name.endswith("/" + MONITORING_OVERLAY)


def split_services(configured, without_monitoring):
    """(core, monitoring) in configured order; without_monitoring lists the services of the same
    selection with the monitoring overlay removed, or None when the overlay is not selected."""
    configured = [name for name in configured if name]
    if without_monitoring is None:
        return configured, []
    core = set(without_monitoring)
    return [name for name in configured if name in core], [name for name in configured if name not in core]


def checked(result, args):
    """Compose callers may return a failed result instead of raising; treat both the same."""
    if result.returncode:
        raise subprocess.CalledProcessError(result.returncode, list(args), getattr(result, "stdout", None))
    return result


def listed(dc, *args, **kwargs):
    return checked(dc(*args, "config", "--services", capture=True, check=True, **kwargs), args).stdout.splitlines()


def release_roles(dc, names):
    """Roles for a release's explicit Compose file list (update and rollback); dc(selection, *args,
    **kwargs) runs Compose for that release with the given file names."""
    def services(selection):
        return listed(lambda *args, **kwargs: dc(selection, *args, **kwargs))
    kept = [name for name in names if not is_monitoring_overlay(name)]
    return split_services(services(names), services(kept) if len(kept) != len(names) else None)


def environment_selection():
    """The COMPOSE_FILE names Compose uses here: the environment, else ./.env as Compose reads it."""
    selection = os.environ.get("COMPOSE_FILE") or ""
    if not selection and Path(".env").is_file():
        from .envfile import read_env, value
        selection = value(read_env(Path(".env")), "COMPOSE_FILE")
    return [name for name in selection.split(":") if name]


def environment_monitoring(dc=compose):
    """Monitoring services of the environment's selection; no Compose call when the overlay is off."""
    names = environment_selection()
    kept = [name for name in names if not is_monitoring_overlay(name)]
    if len(kept) == len(names):
        return []
    base = set(listed(dc, env=dict(os.environ, COMPOSE_FILE=":".join(kept))))
    return [name for name in listed(dc) if name and name not in base]


def environment_roles(dc=compose):
    """(core, monitoring) for the environment's selection (the launcher, restore and rotation paths)."""
    configured = listed(dc)
    names = environment_selection()
    kept = [name for name in names if not is_monitoring_overlay(name)]
    if len(kept) == len(names):
        return split_services(configured, None)
    return split_services(configured, listed(dc, env=dict(os.environ, COMPOSE_FILE=":".join(kept))))


def failures(rows, services):
    """Each listed service that is not running healthy or a one-shot that exited 0, with its state."""
    seen, failed = set(), []
    for row in rows:
        fields = row.split("\t")
        if len(fields) != 4 or fields[0] not in services:
            continue
        service, state, health, code = fields
        seen.add(service)
        if state == "running" and health in ("", "healthy"):
            continue
        if state == "exited" and code == "0":
            continue
        if state == "running":
            failed.append((service, health))
        elif state == "exited":
            failed.append((service, "exited with status " + code))
        else:
            failed.append((service, state or "unknown"))
    return failed + [(service, "not created") for service in services if service not in seen]


def report(failed):
    for service, state in failed:
        warn(f"monitoring service {service} is {state}; Chronicle itself is running. "
             f"Inspect it with ./chronicle logs {service}")
    if failed:
        warn("monitoring is degraded: dashboards, metrics, logs or alerts may be missing until it is healthy; "
             "./chronicle doctor reports its state")


def start_monitoring(dc, services, options=(), timeout=MONITORING_WAIT_TIMEOUT_SECONDS):
    """Start monitoring and wait a bounded time for its health. Never raises for a monitoring
    failure: it warns, naming each service, and returns the failed (service, state) pairs."""
    if not services:
        return []
    try:
        # Compose bounds the health wait; the process bound covers a stalled daemon or pull.
        dc("up", "-d", "--wait", "--wait-timeout", timeout, *options, *services, quiet=True,
           timeout=int(timeout) + 120)
        rows = dc("ps", "-a", "--format", PS_FORMAT, *services, capture=True, timeout=60).stdout or ""
    except (OSError, subprocess.SubprocessError) as error:
        warn(f"could not start or inspect monitoring ({error})")
        rows = ""
    failed = failures(rows.splitlines(), services)
    report(failed)
    return failed


def awaited_by_update(core):
    """(waited, unawaited): the core services an update or rollback waits on, and the rest."""
    return ([service for service in core if service not in UNAWAITED_BY_UPDATE],
            [service for service in core if service in UNAWAITED_BY_UPDATE])


def report_unawaited(dc, services):
    """After a commit: say which unawaited services are still starting, warn about any that failed.
    Never raises; doctor reports the same state later."""
    if not services:
        return []
    try:
        rows = dc("ps", "-a", "--format", PS_FORMAT, *services, capture=True, timeout=60).stdout or ""
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        warn(f"could not inspect {', '.join(services)} ({error}); ./chronicle doctor reports its state")
        return []
    # A service still in its start period is "starting" (db-backup taking its first dump).
    states = failures(rows.splitlines(), services)
    for service, state in states:
        if service == "db-backup" and state == "starting":
            print("db-backup is taking its first backup since this start; ./chronicle doctor reports when it "
                  "has finished, and the safety dump taken before the update is kept meanwhile.")
        elif state == "starting":
            print(f"{service} is still starting; ./chronicle doctor reports its state.")
        else:
            warn(f"{service} is {state}; Chronicle itself is running. Inspect it with ./chronicle logs {service}, "
                 "correct the first error, then run ./chronicle up")
    return states


def start_unawaited(dc, services, options=()):
    """Start services an update does not wait on, after the waited ones are healthy. Never raises:
    a service that could not start is reported by report_unawaited and doctor."""
    if not services:
        return
    try:
        # --no-deps: their dependencies were just started and waited on; don't recreate them again.
        dc("up", "-d", "--no-deps", *options, *services, quiet=True, timeout=PREPARATION_TIMEOUT_SECONDS)
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        warn(f"could not start {', '.join(services)} ({error}); Chronicle itself is running. "
             "./chronicle doctor reports its state")


def start_split(dc, core, monitoring, timeout, options=(), unawaited=()):
    """Wait on core services (raising if one is not healthy), start the unawaited core services
    without a wait, then start monitoring separately.
    The only place operator Python passes --wait to Compose (ast-grep rule selfhost-compose-wait-owner)."""
    if core:  # `up` with no service names would start every configured service.
        arguments = ("up", "-d", "--wait", "--wait-timeout", timeout, *options, *core)
        checked(dc(*arguments, check=True), arguments)
    later = [option for option in options if option != "--remove-orphans"]
    start_unawaited(dc, list(unawaited), later)
    return start_monitoring(dc, monitoring, later)


def monitoring_health():
    """(service, state) for every configured monitoring service (doctor). A working service is
    "healthy", or "completed" for a one-shot that exited 0; anything else is its failure state."""
    services = environment_monitoring()
    if not services:
        return []
    rows = compose("ps", "-a", "--format", PS_FORMAT, *services, capture=True, check=True).stdout.splitlines()
    failed = dict(failures(rows, services))
    completed = {row.split("\t")[0] for row in rows if row.split("\t")[1:2] == ["exited"]}
    return [(service, failed.get(service, "completed" if service in completed else "healthy")) for service in services]


CONFIG_HASH_LABEL = "com.docker.compose.config-hash"


def config_drift():
    """Running services whose container was created from a different configuration than Compose
    renders now (PR-O13), sorted. Compose records each container's configuration hash in the
    CONFIG_HASH_LABEL label and prints the current one with `config --hash`: they differ after an
    .env or Compose edit that no `./chronicle up` applied, because reconcile starts with
    --no-recreate. A running service the configuration no longer has counts too."""
    rendered = compose("config", "--hash", "*", capture=True, stderr=subprocess.PIPE, timeout=30)
    if rendered.returncode:
        raise ValueError("docker compose config --hash failed: " + (rendered.stderr or "").strip()[:200])
    current = dict(line.split(None, 1) for line in rendered.stdout.splitlines() if line.strip())
    running = compose("ps", "--status", "running", "--format", "{{.Service}}\t{{.Label \"" + CONFIG_HASH_LABEL + "\"}}",
                      capture=True, stderr=subprocess.PIPE, timeout=30)
    if running.returncode:
        raise ValueError("docker compose ps failed: " + (running.stderr or "").strip()[:200])
    drifted = set()
    for line in running.stdout.splitlines():
        service, _, recorded = line.partition("\t")
        if service and current.get(service, "").strip() != recorded.strip():
            drifted.add(service)
    return sorted(drifted)


def config_drift_row():
    """The doctor row (id, status, summary, action) for config_drift; a warning, never a failure:
    the running services still work, they only lack an edit that has not been applied."""
    try:
        drifted = config_drift()
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        return ("config-drift", "warn", f"Could not compare running services with the configuration: {error}",
                "Run docker compose config and correct the reported error")
    if not drifted:
        return ("config-drift", "ok", "Running services match the current .env and Compose files", "none")
    return ("config-drift", "warn",
            "Running with settings older than .env or the Compose files: " + ", ".join(drifted),
            "./chronicle up applies them (scheduled reconciliation keeps running containers as they are)")
